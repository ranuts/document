import { afterEach, expect, it, vi } from 'vitest';
import { createComposerSelection } from '../../lib/agent-plugin/ui/composer-selection';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
afterEach(() => document.body.replaceChildren());
it('uses a native keyboard disclosure with a right-hand decorative chevron and synchronized accessibility state', () => {
  const view = createComposerSelection();
  document.body.append(view.el);
  view.label.textContent = 'Selected text · 40 characters';
  view.text.textContent = 'Selected original text';
  expect(view.trigger.tagName).toBe('BUTTON');
  expect(view.trigger.type).toBe('button');
  expect(view.trigger.getAttribute('aria-controls')).toBe(view.reveal.id);
  expect(view.trigger.getAttribute('aria-expanded')).toBe('false');
  expect(view.reveal.getAttribute('aria-hidden')).toBe('true');
  expect(view.trigger.lastElementChild?.tagName.toLowerCase()).toBe('svg');
  view.trigger.click();
  expect(view.trigger.getAttribute('aria-expanded')).toBe('true');
  expect(view.reveal.getAttribute('aria-hidden')).toBe('false');
  expect(view.text.tabIndex).toBe(0);
  view.trigger.click();
  expect(view.trigger.getAttribute('aria-expanded')).toBe('false');
  expect(view.text.tabIndex).toBe(-1);
});
it('reverses repeated toggles without timers or replacing selected text and preserves source updates and scrolling', () => {
  const timer = vi.spyOn(window, 'setTimeout');
  const view = createComposerSelection();
  document.body.append(view.el);
  const text = view.text;
  text.textContent = 'Original selection';
  text.scrollTop = 45;
  for (let count = 0; count < 7; count++) view.trigger.click();
  expect(view.trigger.getAttribute('aria-expanded')).toBe('true');
  view.label.textContent = 'Updated selection';
  text.textContent = 'Updated selection with line\nbreaks';
  expect(view.text).toBe(text);
  expect(text.scrollTop).toBe(45);
  expect(view.trigger.getAttribute('aria-expanded')).toBe('true');
  expect(view.trigger.querySelector('svg')).not.toBeNull();
  expect(timer).not.toHaveBeenCalled();
  timer.mockRestore();
});
it('animates both size directions through CSS with clipped content and a reduced-motion guard', () => {
  const css = readFileSync(resolve(__dirname, '../../styles/assistant.css'), 'utf8');
  expect(css).toMatch(/\.agent-selection-reveal\s*\{[^}]*grid-template-rows:\s*0fr/s);
  expect(css).toMatch(/data-open=['"]true['"]\][^{]*\.agent-selection-reveal\s*\{[^}]*grid-template-rows:\s*1fr/s);
  expect(css).toMatch(/transition:[^;}]*grid-template-rows/s);
  expect(css).toMatch(/prefers-reduced-motion:\s*reduce[^}]*agent-selection-reveal[^}]*transition:\s*none/s);
});
